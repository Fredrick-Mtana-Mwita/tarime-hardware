import { test, expect } from '@playwright/test'
test('Pages subpath works without a backend and never accepts private account details', async ({ page }, info) => {
  const errors: string[] = [], api: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (new URL(r.url()).pathname.startsWith('/api/')) api.push(r.url()) })
  await page.goto('./')
  await expect(page.getByLabel('Client preview notice')).toBeVisible()
  await expect(page.locator('.product-card')).toHaveCount(8)
  await expect.poll(() => page.locator('.hero>img').evaluate((e: HTMLImageElement) => e.complete && e.naturalWidth > 0)).toBe(true)
  await page.locator('.product-card').first().click()
  await expect(page.locator('.main-product-image')).toBeVisible()
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.getByRole('link', { name: 'View cart', exact: true }).click()
  await expect(page.locator('.commerce-summary')).toContainText('Items subtotal')
  await page.getByRole('link', { name: 'Continue to checkout' }).click()
  await expect(page.getByRole('heading', { name: 'This action needs the full application' })).toBeVisible()
  await page.getByRole('link', { name: 'Inventory preview', exact: true }).click()
  await expect(page.locator('.inventory-card').first()).toBeVisible()
  await expect(page.locator('.staff-shell')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('.inventory-card').first()).toBeVisible()
  await page.getByRole('combobox', { name: 'Branch', exact: true }).selectOption('MWANZA')
  await expect(page.locator('.inventory-quantities dd').first()).toHaveText('0')
  await page.getByRole('button', { name: /Receive stock for/ }).first().click()
  await expect(page.getByLabel(/Quantity received/)).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Preview only — nothing is saved' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Login design', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toBeDisabled()
  await page.goto('./#/register')
  await expect(page.getByLabel('Full name', { exact: true })).toBeDisabled()
  await page.goto('./#/staff/login')
  await expect(page.getByLabel('Staff username', { exact: true })).toBeDisabled()
  await page.goto('./#/staff/inventory')
  await expect(page.locator('.inventory-card').first()).toBeVisible()
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`pages-inventory-${width}.png`), fullPage: true })
  }
  expect(errors).toEqual([])
  expect(api).toEqual([])
})
