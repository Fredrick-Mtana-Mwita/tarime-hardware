import { expect, test } from '@playwright/test'
const product = '/#/product/00000000-0000-4000-8000-000000000100'
const phone = () => '+2557' + Math.floor(Math.random() * 100000000).toString().padStart(8, '0')
const password = 'Materials for our next build 2026!'

test('guest cart survives registration and delivery request appears in private orders and updates', async ({ page }, info) => {
  await page.goto(product)
  await page.getByLabel('Quantity (50 kg bag)').fill('2')
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.getByRole('link', { name: 'View cart', exact: true }).click()
  await expect(page.locator('.commerce-summary')).toContainText('TSh 37,000')
  await page.getByRole('spinbutton', { name: 'Quantity', exact: true }).fill('3')
  await page.getByRole('heading', { name: 'Your cart', exact: true }).click()
  await expect(page.locator('.commerce-summary')).toContainText('TSh 55,500')
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'Quantity', exact: true })).toHaveValue('3')
  await page.getByRole('link', { name: 'Continue to checkout' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in to place your request' })).toBeVisible()
  await page.getByRole('link', { name: 'Create an account', exact: true }).click()
  await expect(page.locator('header,footer')).toHaveCount(0)
  await page.getByLabel('Full name', { exact: true }).fill('Asha Builder')
  await page.getByLabel('Phone number', { exact: true }).fill(phone())
  await page.getByLabel('Password', { exact: true }).fill(password)
  const [registered] = await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/auth/register') && r.request().method() === 'POST'), page.getByRole('button', { name: 'Create account', exact: true }).click()])
  expect(registered.status()).toBe(201)
  await page.getByLabel('Choose your branch').selectOption('TARIME')
  await expect(page.getByRole('heading', { name: 'Contact & fulfilment' })).toBeVisible()
  await expect(page.getByLabel('Contact name')).toHaveValue('Asha Builder')
  await page.getByLabel('Delivery address').fill('Sample address, Mwanza â€” near the test market')
  await page.getByLabel('Instructions (optional)').fill('Please call before arranging delivery.')
  await page.getByRole('checkbox').check()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.screenshot({ path: info.outputPath('checkout-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Submit order request' }).click()
  await expect(page.getByRole('heading', { name: 'Order request received' })).toBeVisible()
  await expect(page.locator('.commerce-summary')).toContainText('Awaiting delivery fee')
  await expect(page.getByText('Stock has not been reserved yet.', { exact: false })).toBeVisible()
  await expect(page.locator('.cart-header-link')).toHaveAttribute('aria-label', 'Cart (0)')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Order request received' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.screenshot({ path: info.outputPath('order-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'My orders & updates', exact: true }).click()
  await expect(page.locator('.order-list-card')).toHaveCount(1)
  await expect(page.locator('.notifications')).toContainText('Order request received')
  await page.getByRole('button', { name: 'Mark as read', exact: true }).click()
  await expect(page.locator('.notifications .notice-unread')).toHaveCount(0)
  await page.goto('/#/cart')
  await expect(page.getByRole('heading', { name: 'Your cart is empty' })).toBeVisible()
})

test('pickup retry after a lost response returns the existing request and keeps one order', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/register')
  await page.getByLabel('Full name', { exact: true }).fill('Juma Pickup')
  await page.getByLabel('Phone number', { exact: true }).fill(phone())
  await page.getByLabel('Password', { exact: true }).fill(password)
  const [registered] = await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/auth/register') && r.request().method() === 'POST'), page.getByRole('button', { name: 'Create account', exact: true }).click()])
  expect(registered.status()).toBe(201)
  await expect(page.getByRole('heading', { name: 'Welcome, Juma Pickup' })).toBeVisible()
  await page.goto(product)
  await page.getByRole('button', { name: '25 kg bag', exact: true }).click()
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.goto('/#/checkout')
  await page.getByLabel('Choose your branch').selectOption('TARIME')
  await page.getByRole('radio', { name: 'Shop pickup', exact: true }).check()
  await expect(page.getByLabel('Delivery address')).toHaveCount(0)
  await page.getByRole('checkbox').check()
  const keys: string[] = []
  let loseResponse = true
  await page.route('**/api/orders', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    keys.push(route.request().headers()['idempotency-key'])
    if (loseResponse) { loseResponse = false; const response = await route.fetch(); expect(response.status()).toBe(201); await route.abort() }
    else await route.continue()
  })
  await page.getByRole('button', { name: 'Submit order request' }).click()
  await expect(page.getByRole('alert')).toContainText('retrying the same details')
  await expect(page.locator('.cart-header-link')).toHaveAttribute('aria-label', 'Cart (1)')
  await page.getByRole('button', { name: 'Submit order request' }).click()
  await expect(page.getByRole('heading', { name: 'Order request received' })).toBeVisible()
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
  await expect(page.locator('.commerce-summary')).toContainText('TSh 10,500')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.screenshot({ path: info.outputPath('order-mobile.png'), fullPage: true })
  await page.getByRole('link', { name: 'My orders & updates', exact: true }).click()
  await expect(page.locator('.order-list-card')).toHaveCount(1)
})

test('cart quantity rules, removal and quote failure are recoverable', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto(product)
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.goto('/#/cart')
  await expect(page.locator('.commerce-summary')).toContainText('TSh 18,500')
  await page.getByRole('spinbutton', { name: 'Quantity', exact: true }).fill('1.5')
  await page.getByRole('heading', { name: 'Your cart', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('positive quantity')
  await expect(page.getByRole('button', { name: 'Fix quantities to continue' })).toBeDisabled()
  await page.getByRole('spinbutton', { name: 'Quantity', exact: true }).fill('2')
  await page.getByRole('heading', { name: 'Your cart', exact: true }).click()
  await expect(page.locator('.commerce-summary')).toContainText('TSh 37,000')
  await page.route('**/api/cart/quote', route => route.abort())
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('could not reach the shop')
  await expect(page.getByRole('link', { name: 'Continue to checkout' })).toHaveCount(0)
  await page.unroute('**/api/cart/quote')
  await page.getByRole('button', { name: 'Refresh prices', exact: true }).click()
  await expect(page.locator('.commerce-summary')).toContainText('TSh 37,000')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.screenshot({ path: info.outputPath('cart-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Remove Portland Cement 42.5R' }).click()
  await expect(page.getByRole('heading', { name: 'Your cart is empty' })).toBeVisible()
})

test('signing in through the header tab restores checkout identity and retains the guest cart', async ({ page }) => {
  await page.goto(product)
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  const opened = page.waitForEvent('popup')
  await page.locator('.account-link').click()
  const auth = await opened
  await auth.getByRole('link', { name: 'Create an account', exact: true }).click()
  await auth.getByLabel('Full name', { exact: true }).fill('Tab Customer')
  await auth.getByLabel('Phone number', { exact: true }).fill(phone())
  await auth.getByLabel('Password', { exact: true }).fill(password)
  const registered = auth.waitForResponse(response => response.url().endsWith('/api/auth/register') && response.request().method() === 'POST')
  await auth.getByRole('button', { name: 'Create account', exact: true }).click()
  expect((await registered).status()).toBe(201)
  await page.bringToFront()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page.locator('.account-link')).toHaveText('My account')
  await page.goto('/#/checkout')
  await page.getByLabel('Choose your branch').selectOption('TARIME')
  await expect(page.getByLabel('Contact name')).toHaveValue('Tab Customer')
  await expect(page.locator('.cart-header-link')).toHaveAttribute('aria-label', 'Cart (1)')
  await auth.close()
})
