import { expect, test } from '@playwright/test'

test('homepage loads database catalogue, category counts, images and product links', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Cement, steel and roofing for every site.' })).toBeVisible()
  await expect(page.locator('.category-tile')).toHaveCount(17)
  await expect(page.locator('.product-card')).toHaveCount(8)
  await expect(page.getByText('Preview catalogue', { exact: false })).toBeVisible()
  const image = page.locator('.hero > img')
  await expect(image).toBeVisible()
  expect(await image.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
  await expect(page.locator('main')).toHaveAttribute('id', 'main')
  await page.screenshot({ path: info.outputPath('home-desktop.png'), fullPage: true })
  expect((await page.request.get('/api/admin/orders')).status()).toBe(401)
})

test('search, no-results and clear filters are real API workflows', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('searchbox', { name: 'Search products' }).fill('PPR')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'PPR Pipe 25 mm, 4 m' })).toBeVisible()
  await expect(page.locator('.stock-badge')).toHaveText('Out of stock')
  await page.getByRole('searchbox').fill('no-product-like-this')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No products found' })).toBeVisible()
  await page.getByRole('link', { name: 'Clear filters', exact: true }).click()
  await expect(page.locator('.product-card')).toHaveCount(12)
})

test('phone filters, URL restoration and sorting work without horizontal overflow', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/shop')
  await page.getByLabel('Category', { exact: true }).selectOption('electrical')
  await page.getByLabel('Maximum', { exact: true }).fill('10000')
  await page.getByLabel('In stock only').check()
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByLabel('Sort', { exact: true }).selectOption('price-desc')
  await page.reload()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await expect(page.getByLabel('Maximum', { exact: true })).toHaveValue('10000')
  await expect(page.getByLabel('Category', { exact: true })).toHaveValue('electrical')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('shop-mobile.png'), fullPage: true })
})

test('product variants use database prices and gallery controls work', async ({ page }, info) => {
  await page.goto('/#/product/00000000-0000-4000-8000-000000000100')
  await expect(page.getByRole('heading', { name: 'Portland Cement 42.5R' })).toBeVisible()
  await expect(page.locator('.detail-price')).toHaveText('TSh 18,500')
  await page.getByRole('button', { name: '25 kg bag', exact: true }).click()
  await expect(page.locator('.detail-price')).toHaveText('TSh 10,500')
  await expect(page.locator('.sku')).toHaveText('FPA-SAMPLE-001-02')
  await page.getByRole('button', { name: 'View Cement bag - illustrative alternate photo' }).click()
  await expect(page.locator('.main-product-image')).toHaveAttribute('src', '/images/cement-sack.jpg')
  await expect(page.getByRole('heading', { name: 'Specifications' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.screenshot({ path: info.outputPath('product-desktop.png'), fullPage: true })
  await page.goto('/#/product/00000000-0000-4000-8000-999999999999')
  await expect(page.getByRole('alert')).toContainText('This product is not available.')
})

test('failed catalogue requests expose retry and never show fake products', async ({ page }) => {
  await page.route('**/api/products?**', route => route.abort())
  await page.goto('/#/shop')
  await expect(page.getByRole('alert')).toContainText('We could not load the catalogue')
  await expect(page.locator('.product-card')).toHaveCount(0)
  await page.unroute('**/api/products?**')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.locator('.product-card')).toHaveCount(12)
})
