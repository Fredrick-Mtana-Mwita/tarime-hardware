import { expect, test } from '@playwright/test'
import { existsSync, readFileSync } from 'node:fs'
const file = process.env.FPA_STAFF_TEST_FIXTURES || ''
const enabled = !!file && existsSync(file) && process.env.FPA_BACKEND_PORT === '18080' && process.env.FPA_FRONTEND_PORT === '15173'
const fixture = enabled ? JSON.parse(readFileSync(file, 'utf8')) as { sales: string; password: string } : null
test.skip(!enabled, 'Requires isolated test-only staff fixture and server ports.')

test('customer selects branch, Sales confirms and customer sees reserved order', async ({ page, browser }, info) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/register')
  await page.getByLabel('Full name', { exact: true }).fill('Branch browser customer')
  await page.getByLabel('Phone number', { exact: true }).fill('+2557' + Math.floor(Math.random() * 100000000).toString().padStart(8, '0'))
  await page.getByLabel('Password', { exact: true }).fill('Branch customer private password 2026!')
  const [registered] = await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/auth/register') && r.request().method() === 'POST'), page.getByRole('button', { name: 'Create account', exact: true }).click()])
  expect(registered.status()).toBe(201)
  await expect(page.getByRole('heading', { name: 'Welcome, Branch browser customer' })).toBeVisible()
  await page.goto('/#/product/00000000-0000-4000-8000-000000000100')
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.goto('/#/checkout')
  await expect(page.getByRole('button', { name: 'Submit order request' })).toHaveCount(0)
  await page.getByLabel('Choose your branch').selectOption('MWANZA')
  await expect(page.getByRole('alert')).toContainText('Not enough stock')
  await expect(page.getByRole('button', { name: 'Submit order request' })).toHaveCount(0)
  await page.getByLabel('Choose your branch').selectOption('TARIME')
  await page.getByRole('radio', { name: 'Shop pickup' }).check()
  await page.getByRole('checkbox').check()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('branch-checkout-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Submit order request' }).click()
  await expect(page.getByRole('heading', { name: 'Order request received' })).toBeVisible()
  const id = page.url().split('/orders/')[1]
  await expect(page.locator('.contact-details')).toContainText('Tarime (main branch)')
  const context = await browser.newContext()
  const staff = await context.newPage()
  await staff.goto('/#/staff/login')
  await staff.getByLabel('Staff username', { exact: true }).fill(fixture!.sales)
  await staff.getByLabel('Password', { exact: true }).fill(fixture!.password)
  const [signedIn] = await Promise.all([staff.waitForResponse(r => r.url().endsWith('/api/staff/auth/login')), staff.getByRole('button', { name: 'Sign in to staff workspace' }).click()]); expect(signedIn.status()).toBe(200)
  await expect(staff.getByRole('heading', { name: 'Choose your private password' })).toBeVisible()
  await staff.getByLabel('Current password', { exact: true }).fill(fixture!.password)
  await staff.getByLabel('New password', { exact: true }).fill('Private branch sales browser passphrase 2026!')
  await staff.getByLabel('Repeat new password', { exact: true }).fill('Private branch sales browser passphrase 2026!')
  const [changed] = await Promise.all([staff.waitForResponse(r => r.url().endsWith('/api/staff/auth/password')), staff.getByRole('button', { name: 'Save private password' }).click()]); expect(changed.status()).toBe(200)
  await expect(staff.getByRole('heading', { name: 'Ready for the next build.', exact: true })).toBeVisible()
  await staff.goto('/#/staff/orders/' + id)
  await staff.getByLabel('Customer agreement record').fill('Customer agreed today by phone to Tarime pickup, one bag and total 18,500 TZS.')
  await staff.getByRole('checkbox').check()
  await staff.screenshot({ path: info.outputPath('branch-confirm-desktop.png'), fullPage: true })
  await staff.getByRole('button', { name: 'Confirm and reserve stock' }).click()
  await expect(staff.locator('.staff-review-note')).toContainText('Status: confirmed')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Your order', exact: true })).toBeVisible()
  await expect(page.locator('.eyebrow')).toContainText('Confirmed')
  await page.goto('/#/orders')
  await expect(page.locator('.notifications')).toContainText('Order confirmed')
  await context.close()
})
